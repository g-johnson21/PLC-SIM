#!/usr/bin/env node
// Embeds backend/examples/*.st|*.ld.json|*.sfc.json into src/protocol/examples.generated.ts
// so the dev mock can serve them as welcome.examples without a filesystem or server.
// Run manually after backend/examples/ changes: node scripts/copy-examples.mjs

import { readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
import { dirname, join } from 'node:path';

const here = dirname(fileURLToPath(import.meta.url));
const examplesDir = join(here, '..', '..', 'backend', 'examples');
const outPath = join(here, '..', 'src', 'protocol', 'examples.generated.ts');

const files = readdirSync(examplesDir).sort();
const examples = files.map((file) => {
  const text = readFileSync(join(examplesDir, file), 'utf-8');
  if (file.endsWith('.ld.json')) {
    return { name: file.replace(/\.ld\.json$/, ''), language: 'LD', source: JSON.parse(text) };
  }
  if (file.endsWith('.sfc.json')) {
    return { name: file.replace(/\.sfc\.json$/, ''), language: 'SFC', source: JSON.parse(text) };
  }
  if (file.endsWith('.st')) {
    return { name: file.replace(/\.st$/, ''), language: 'ST', source: text };
  }
  return null;
}).filter(Boolean);

const banner = `// GENERATED by frontend/scripts/copy-examples.mjs from backend/examples/.
// Do not hand-edit; re-run the script after the example programs change.
`;

const body = `${banner}
import type { ProgramSource } from './types';

export const EXAMPLES: ProgramSource[] = ${JSON.stringify(examples, null, 2)};
`;

writeFileSync(outPath, body, 'utf-8');
console.log(`wrote ${examples.length} examples to ${outPath}`);
